#!/bin/bash
# Writes the production .env from /etc/task-api/deploy.env (non-secret, written by Terraform's user_data)
# and SecureString parameters under $SSM_PARAMETER_PREFIX in SSM Parameter Store. Runs on the server as root.
set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
DEPLOY_ENV_FILE="${DEPLOY_ENV_FILE:-/etc/task-api/deploy.env}"
# shellcheck source=/dev/null
. "$DEPLOY_ENV_FILE"
export AWS_REGION

param() {
    aws ssm get-parameter --with-decryption --name "${SSM_PARAMETER_PREFIX}/$1" --query Parameter.Value --output text
}

# Secrets are written single-quoted so Compose doesn't expand "$" in them; that rules out quotes and newlines inside them
quoted() {
    case "$1" in
        *"'"* | *$'\n'*)
            echo "ERROR: SSM parameter $2 contains a single quote or newline, which .env can't hold" >&2
            exit 1
            ;;
    esac
    printf "'%s'" "$1"
}

# Plain assignments, so a missing parameter or a rejected value stops the script before .env is touched
POSTGRES_PASSWORD="$(param postgres-password)"
SECRET_KEY="$(param secret-key)"
GF_SECURITY_ADMIN_PASSWORD="$(param grafana-admin-password)"
CF_DNS_API_TOKEN="$(param cloudflare-dns-api-token)"
Q_POSTGRES_PASSWORD="$(quoted "$POSTGRES_PASSWORD" postgres-password)"
Q_SECRET_KEY="$(quoted "$SECRET_KEY" secret-key)"
Q_GF_SECURITY_ADMIN_PASSWORD="$(quoted "$GF_SECURITY_ADMIN_PASSWORD" grafana-admin-password)"
Q_CF_DNS_API_TOKEN="$(quoted "$CF_DNS_API_TOKEN" cloudflare-dns-api-token)"

POSTGRES_USER=app
POSTGRES_DB=app
# The password may contain URL-reserved characters, so encode it for DATABASE_URL
ENCODED_PASSWORD="$(python3 -c 'import sys, urllib.parse; print(urllib.parse.quote(sys.argv[1], safe=""))' "$POSTGRES_PASSWORD")"

umask 077
tmp="$(mktemp "${APP_DIR}/.env.XXXXXX")"
cat > "$tmp" <<EOF
# Generated by deploy/render-env.sh on every deploy; edit the SSM parameters or deploy.env instead
POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${Q_POSTGRES_PASSWORD}
POSTGRES_DB=${POSTGRES_DB}
DATABASE_URL=postgresql://${POSTGRES_USER}:${ENCODED_PASSWORD}@db:5432/${POSTGRES_DB}

SECRET_KEY=${Q_SECRET_KEY}
ACCESS_TOKEN_EXPIRE_MINUTES=30
ENABLE_DOCS=${ENABLE_DOCS:-false}

GF_SECURITY_ADMIN_PASSWORD=${Q_GF_SECURITY_ADMIN_PASSWORD}
# Grafana is only reachable through an SSM port forward to localhost:3000 (see README)
GF_SERVER_ROOT_URL=http://localhost:3000/grafana

BACKUP_INTERVAL_SECONDS=86400
BACKUP_KEEP_DAYS=7
BACKUP_S3_BUCKET=${BACKUP_S3_BUCKET}
AWS_REGION=${AWS_REGION}

DOMAIN=${DOMAIN}
ACME_EMAIL=${ACME_EMAIL}
CF_DNS_API_TOKEN=${Q_CF_DNS_API_TOKEN}
EOF
mv "$tmp" "${APP_DIR}/.env"
echo "Wrote ${APP_DIR}/.env"
